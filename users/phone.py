"""Утилиты нормализации, валидации и форматирования телефонных номеров.

Модуль лежит в приложении ``users``, потому что телефон — атрибут
профиля пользователя. Другие приложения (например, ``orders`` для
формы чекаута) импортируют утилиты отсюда: ``from users.phone import ...``.

В БД хранится единый формат ``+7XXXXXXXXXX`` (11 цифр с кодом страны):
- удобно искать и сравнивать;
- удобно валидировать;
- отображение вынесено в отдельную функцию ``format_phone``.
"""

import re

from django.core.validators import RegexValidator

# Формат хранения: +7XXXXXXXXXX (11 цифр).
_DIGITS_ONLY = re.compile(r'\D')
_DISPLAY_PATTERN = re.compile(r'^\+7(\d{3})(\d{3})(\d{2})(\d{2})$')

# Валидатор принимает свободный формат ввода:
# +7 (999) 123-45-67, 89991234567, 7 999 123 45 67, +79991234567.
# Ограничение на код региона отсутствует — любой 3-значный код допустим.
phone_validator = RegexValidator(
    regex=r'^(\+7|7|8)?[\s\-]?\(?[0-9]{3}\)?[\s\-]?[0-9]{3}[\s\-]?[0-9]{2}[\s\-]?[0-9]{2}$',
    message=('Введите корректный номер телефона (например, +7 (999) 123-45-67 или 89991234567).'),
)


def normalize_phone(value: str) -> str:
    """Приводит телефон к единому формату ``+7XXXXXXXXXX``.

    Логика:
    - удаляет все нецифровые символы;
    - 10 цифр → добавляет ``7`` в начало;
    - 11 цифр, начинающихся с ``8`` → заменяет ``8`` на ``7``;
    - 11 цифр, начинающихся с ``7`` → оставляет как есть;
    - результат — ``+7`` + 10 цифр.

    Args:
        value: Строка в свободной форме: ``'+7 (999) 123-45-67'``,
            ``'89991234567'``, ``'7 999 123 45 67'`` и т. п.

    Returns:
        str: Нормализованный номер в формате ``+7XXXXXXXXXX``.
        Пустая строка → пустая строка (поле может быть необязательным).

    Raises:
        ValueError: Если после удаления нецифровых символов длина
            не 10 и не 11, либо первая цифра не 7/8 (для 11-значных).

    Examples:
        >>> normalize_phone('+7 (999) 123-45-67')
        '+79991234567'
        >>> normalize_phone('89991234567')
        '+79991234567'
        >>> normalize_phone('9991234567')
        '+79991234567'
        >>> normalize_phone('')
        ''
    """
    if not value or not value.strip():
        return ''

    digits = _DIGITS_ONLY.sub('', value)

    if len(digits) == 10:
        digits = '7' + digits
    elif len(digits) == 11 and digits[0] == '8':
        digits = '7' + digits[1:]
    elif len(digits) == 11 and digits[0] == '7':
        pass  # уже в нужном виде
    else:
        raise ValueError(f'Некорректная длина номера: {len(digits)} цифр. Ожидается 10 или 11.')

    return f'+{digits}'


def format_phone(value: str) -> str:
    """Форматирует нормализованный номер для отображения.

    Args:
        value: Номер в формате ``+7XXXXXXXXXX``.

    Returns:
        str: ``'+7 (999) 123-45-67'`` или исходная строка, если формат
        не совпадает (чтобы не потерять данные при рендере).

    Examples:
        >>> format_phone('+79991234567')
        '+7 (999) 123-45-67'
        >>> format_phone('some garbage')
        'some garbage'
    """
    match = _DISPLAY_PATTERN.match(value)
    if not match:
        return value
    return f'+7 ({match.group(1)}) {match.group(2)}-{match.group(3)}-{match.group(4)}'
